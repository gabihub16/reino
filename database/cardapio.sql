-- Armazena o catalogo de produtos exibido no cardapio e administrado pelo sistema.
CREATE TABLE IF NOT EXISTS produtos (
    -- Identificador gerado automaticamente para cada produto.
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nome, marca, categoria e descricao apresentados nas telas do catalogo.
    nome VARCHAR(150) NOT NULL,
    marca VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    descricao TEXT NOT NULL,
    -- O preco nao pode ser negativo.
    preco NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    -- Define se o item pode ser adicionado ao carrinho.
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    -- A avaliacao pode ficar vazia; quando informada, deve estar entre 0 e 5.
    avaliacao NUMERIC(2, 1) CHECK (avaliacao BETWEEN 0 AND 5),
    -- Guarda o nome ou caminho da imagem associada ao produto.
    imagem TEXT
);

-- Adiciona a disponibilidade em bancos que ja tinham a tabela de produtos.
ALTER TABLE produtos
    ADD COLUMN IF NOT EXISTS ativo BOOLEAN NOT NULL DEFAULT TRUE;

-- Armazena os dados de acesso e contato dos clientes e administradores.
CREATE TABLE IF NOT EXISTS clientes (
    -- Identificador usado tambem para relacionar o cliente ao carrinho.
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    -- Cada conta deve usar um e-mail exclusivo.
    email VARCHAR(255) NOT NULL UNIQUE,
    -- Campo destinado a senha armazenada pelo sistema.
    senha TEXT NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    -- Novos cadastros sao clientes; os perfis aceitos sao cliente e admin.
    perfil VARCHAR(20) NOT NULL DEFAULT 'cliente'
        CHECK (perfil IN ('cliente', 'admin'))
);

-- Registra os produtos e quantidades no carrinho de cada cliente.
CREATE TABLE IF NOT EXISTS carrinho (
    -- Relacionamentos removem os itens do carrinho se a conta ou produto for excluido.
    cliente_id INTEGER NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    produto_id INTEGER NOT NULL REFERENCES produtos (id) ON DELETE CASCADE,
    -- Cada linha deve ter uma quantidade positiva.
    quantidade INTEGER NOT NULL DEFAULT 1 CHECK (quantidade > 0),
    -- Data e hora de inclusao, preenchidas automaticamente.
    adicionado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Impede que o mesmo produto apareca em linhas duplicadas para um cliente.
    PRIMARY KEY (cliente_id, produto_id)
);

-- Registra cada pedido concluido e seu valor total para o dashboard do administrador.
CREATE TABLE IF NOT EXISTS pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL REFERENCES clientes (id) ON DELETE RESTRICT,
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'finalizado'
        CHECK (status IN ('pendente', 'finalizado', 'cancelado')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Armazena os itens de cada pedido para permitir calculos futuros e relatorios.
CREATE TABLE IF NOT EXISTS pedido_itens (
    pedido_id INTEGER NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    produto_id INTEGER NOT NULL REFERENCES produtos (id) ON DELETE RESTRICT,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10, 2) NOT NULL CHECK (preco_unitario >= 0),
    PRIMARY KEY (pedido_id, produto_id)
);

-- Acelera consultas e operacoes de relacionamento pelo identificador do produto.
